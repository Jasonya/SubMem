"""Shared dense retrieval layer (OpenAI embeddings + FAISS).

Used by C1, C3, C4, C5 — all share the same retrieval mechanism.
Each subclass only differs in how write() processes text before indexing.

Encoder: OpenAI text-embedding-3-small (1536d) by default.
Override via config.extra["encoder_model"].
"""
import time
from typing import Any, Dict, List, Optional

import numpy as np

from .base import BaseMemoryUnit, MemoryEntry
from .embeddings import create_encoder


def _latency_percentiles(times_ms: List[float]) -> Dict[str, float]:
    """Compute latency stats with trimmed mean (drop top/bottom 5%) to reduce outlier impact."""
    if not times_ms:
        return {"mean": 0.0, "trimmed_mean": 0.0, "p50": 0.0, "p90": 0.0}
    arr = np.array(times_ms)
    # Trimmed mean: drop top & bottom 5%
    lo, hi = np.percentile(arr, [5, 95])
    trimmed = arr[(arr >= lo) & (arr <= hi)]
    return {
        "mean": float(np.mean(arr)),
        "trimmed_mean": float(np.mean(trimmed)) if len(trimmed) > 0 else float(np.mean(arr)),
        "p50": float(np.median(arr)),
        "p90": float(np.percentile(arr, 90)),
    }


class DenseRetrievalMemory(BaseMemoryUnit):
    """Base class for memory units that use dense embedding + FAISS cosine retrieval.

    Subclasses must implement:
      - write(text, metadata) — process text and call _add_to_index()
      - Optionally override _on_reset() for cleanup
    """

    def __init__(self, config, model):
        super().__init__(config, model)
        self._entries: List[MemoryEntry] = []
        self._index = None
        self._enc = None  # BaseEncoder instance
        self._write_times: List[float] = []
        self._read_times: List[float] = []
        # Token consumption tracking
        self._token_counts = {
            "write_llm_input": 0,   # tokens sent to LLM during write (C4/C5)
            "write_llm_output": 0,  # tokens generated by LLM during write (C4/C5)
            "write_llm_calls": 0,   # number of LLM calls during write
            "read_context_tokens": 0,  # total tokens in retrieved contexts
            "read_calls": 0,           # number of read() calls
        }
        self._write_call_count = 0
        self._init_encoder()
        self._init_index()

    def _init_encoder(self):
        self._enc = create_encoder(self.config)

    def _init_index(self):
        import faiss
        self._index = faiss.IndexFlatIP(self._enc.dim)

    def _encode(self, texts: List[str]) -> np.ndarray:
        """Encode texts into L2-normalised embeddings."""
        return self._enc.encode(texts)

    def _add_to_index(self, text: str, metadata: Optional[Dict[str, Any]] = None):
        """Encode a single text and add to FAISS index + entries list."""
        self._write_call_count += 1
        emb = self._encode([text])
        self._index.add(emb)
        self._entries.append(MemoryEntry(
            content=text,
            metadata=metadata or {},
            timestamp=len(self._entries),
        ))

    def _add_batch_to_index(self, texts: List[str], metadata: Optional[Dict[str, Any]] = None):
        """Encode and add multiple texts to index in one batch."""
        if not texts:
            return
        embs = self._encode(texts)
        self._index.add(embs)
        for text in texts:
            self._entries.append(MemoryEntry(
                content=text,
                metadata=metadata or {},
                timestamp=len(self._entries),
            ))

    def _track_llm_call(self, prompt: str, response: str):
        """Track token consumption for an LLM call during write (construction)."""
        self._token_counts["write_llm_input"] += len(self.model.encode(prompt))
        self._token_counts["write_llm_output"] += len(self.model.encode(response))
        self._token_counts["write_llm_calls"] += 1

    def _track_mgmt_call(self, prompt: str, response: str):
        """Track token consumption for a management LLM call (dedup, update, delete, resolution)."""
        self._token_counts.setdefault("mgmt_llm_input", 0)
        self._token_counts.setdefault("mgmt_llm_output", 0)
        self._token_counts.setdefault("mgmt_llm_calls", 0)
        self._token_counts["mgmt_llm_input"] += len(self.model.encode(prompt))
        self._token_counts["mgmt_llm_output"] += len(self.model.encode(response))
        self._token_counts["mgmt_llm_calls"] += 1

    # ── read (shared by all dense retrieval units) ──────────

    def read(self, query: str, top_k: int = 10) -> List[MemoryEntry]:
        if self._index.ntotal == 0:
            return []
        t0 = time.perf_counter()
        q_emb = self._encode([query])
        k = min(top_k, self._index.ntotal)
        scores, indices = self._index.search(q_emb, k)
        results = []
        for score, idx in zip(scores[0], indices[0]):
            if idx < 0:
                continue
            entry = self._entries[idx]
            results.append(MemoryEntry(
                content=entry.content,
                metadata=entry.metadata,
                score=float(score),
                timestamp=entry.timestamp,
            ))
        self._read_times.append(time.perf_counter() - t0)
        # Track read token consumption.
        # `read_context_tokens_pool` = tokens across ALL returned pool entries,
        #   useful for recall/efficiency analysis of the retriever itself.
        # `read_context_tokens` (legacy name, kept for table E7) = same value
        #   unless a caller later trims the pool before feeding the prompt,
        #   in which case the runner should overwrite this with the actually-
        #   formatted tokens (see run_alfworld_rollout.retrieve_balanced +
        #   format_refs accounting). We keep pool as the default so single-
        #   benchmark substrates (LoCoMo/BCB) still report correctly.
        self._token_counts["read_calls"] += 1
        pool_tokens = sum(len(self.model.encode(r.content)) for r in results)
        self._token_counts.setdefault("read_context_tokens_pool", 0)
        self._token_counts["read_context_tokens_pool"] += pool_tokens
        self._token_counts["read_context_tokens"] += pool_tokens
        return results

    # ── lifecycle ───────────────────────────────────────────

    def reset(self):
        self._entries.clear()
        self._write_times.clear()
        self._read_times.clear()
        self._token_counts = {
            "write_llm_input": 0,
            "write_llm_output": 0,
            "write_llm_calls": 0,
            "read_context_tokens": 0,
            "read_calls": 0,
        }
        self._init_index()
        self._on_reset()

    def _on_reset(self):
        """Hook for subclasses to clear additional state."""
        pass

    def size(self) -> int:
        return len(self._entries)

    # ── cache: save/load post-write state ───────────────────

    def save_state(self, dir_path: str) -> None:
        """Pickle entries + serialize FAISS index. Subclasses extend if
        they have additional state (override and call super().save_state)."""
        import os, pickle, faiss
        os.makedirs(dir_path, exist_ok=True)
        with open(os.path.join(dir_path, "entries.pkl"), "wb") as f:
            pickle.dump({
                "entries": [(e.content, e.metadata, e.score, e.timestamp)
                            for e in self._entries],
                "token_counts": dict(self._token_counts),
                "write_times": list(self._write_times),
                "write_call_count": self._write_call_count,
                "encoder_dim": self._enc.dim,
            }, f)
        if self._index is not None and self._index.ntotal > 0:
            faiss.write_index(self._index, os.path.join(dir_path, "faiss.index"))

    @classmethod
    def load_state(cls, dir_path: str, config, model):
        """Reconstruct: instantiate normally, then restore entries + index."""
        import os, pickle, faiss
        unit = cls(config, model)
        with open(os.path.join(dir_path, "entries.pkl"), "rb") as f:
            data = pickle.load(f)
        unit._entries = [
            MemoryEntry(content=c, metadata=m, score=s, timestamp=t)
            for (c, m, s, t) in data["entries"]
        ]
        unit._token_counts = data["token_counts"]
        unit._write_times = data["write_times"]
        unit._write_call_count = data["write_call_count"]
        idx_path = os.path.join(dir_path, "faiss.index")
        if os.path.exists(idx_path):
            unit._index = faiss.read_index(idx_path)
        return unit

    # ── stats ──────────────────────────────────────────────

    def get_stats(self) -> Dict[str, Any]:
        stats = super().get_stats()
        read_times_ms = [t * 1000 for t in self._read_times]
        write_times_ms = [t * 1000 for t in self._write_times]
        stats.update({
            "memory_size_bytes": self.get_external_storage_bytes(),
            "token_consumption": dict(self._token_counts),
            "write_call_count": self._write_call_count,
            "read_latency_ms": _latency_percentiles(read_times_ms),
            "write_latency_ms": _latency_percentiles(write_times_ms),
        })
        return stats

    def get_gpu_memory_bytes(self) -> int:
        if hasattr(self._enc, '_model'):
            param_bytes = sum(p.numel() * p.element_size() for p in self._enc._model.parameters())
            return param_bytes if getattr(self._enc, '_device', 'cpu') != 'cpu' else 0
        return 0  # API-based encoder has no local GPU footprint

    def get_external_storage_bytes(self) -> int:
        index_bytes = self._index.ntotal * self._enc.dim * 4
        text_bytes = sum(len(e.content.encode("utf-8")) for e in self._entries)
        return index_bytes + text_bytes

    def get_all_entries(self) -> List[MemoryEntry]:
        return list(self._entries)
